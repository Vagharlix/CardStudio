"""Creates a purple version of every blue frame image used by the frame packs.

For each pack entry named "... Blue ..." (blue only, not hybrids) whose image is
a PNG path, writes "<image>-purple.webp" (and "<image>-purpleThumb.webp") next
to it by rotating hues in HSV space, then lists those images in
web/js/app/purple-frames.js. At runtime web/js/app/ui.js adds a matching
"... Purple ..." entry to each pack, right after the green one.

Usage: python3 scripts/make-purple-frames.py   (needs: pip install numpy pillow)
"""
import glob
import os
import re
from concurrent.futures import ProcessPoolExecutor

import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'web')
HUE_SHIFT = 69      # degrees: blue -> violet (matched on mtgcardbuilder.com's purple frame)
SATURATION = 0.64
VALUE = 0.88

ENTRY = re.compile(r"""name\s*:\s*(['"])([^'"]*?\bBlue\b[^'"]*?)\1\s*,\s*src\s*:\s*(['"])([^'"]+)\3""")
OTHER_COLOR = re.compile(r"\b(White|Black|Red|Green|Gold|Multicolored|Artifact|Land|Colorless|Purple)\b")


def shift(img):
    rgba = np.asarray(img.convert('RGBA')).astype(np.float32) / 255.0
    rgb, alpha = rgba[..., :3], rgba[..., 3:]
    mx, mn = rgb.max(-1), rgb.min(-1)
    d = mx - mn
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    h = np.zeros_like(mx)
    has = d > 1e-6
    i = has & (mx == r); h[i] = ((g - b)[i] / d[i]) % 6
    i = has & (mx == g) & ~(mx == r); h[i] = (b - r)[i] / d[i] + 2
    i = has & (mx == b) & ~(mx == r) & ~(mx == g); h[i] = (r - g)[i] / d[i] + 4
    h = (h * 60 + HUE_SHIFT) % 360
    s0 = np.where(mx > 1e-6, d / np.maximum(mx, 1e-6), 0)
    s = np.clip(s0 * SATURATION, 0, 1)
    # darken the coloured parts only: near-white areas (text box, bars) stay bright
    v = np.clip(mx * (1 - (1 - VALUE) * np.clip(s0 * 2, 0, 1)), 0, 1)
    c = v * s
    hp = h / 60
    x = c * (1 - np.abs(hp % 2 - 1))
    z = np.zeros_like(c)
    conds = [hp < 1, hp < 2, hp < 3, hp < 4, hp < 5, hp >= 5]
    out = np.stack([np.select(conds, [c, x, z, z, x, c]),
                    np.select(conds, [x, c, c, x, z, z]),
                    np.select(conds, [z, z, x, c, c, x])], -1) + (v - c)[..., None]
    data = (np.concatenate([out, alpha], -1) * 255).round().astype(np.uint8)
    return Image.fromarray(data, 'RGBA')


def convert(job):
    src, dst, quality = job
    if os.path.exists(dst) and os.path.getmtime(dst) >= os.path.getmtime(src):
        return 'skip'
    with Image.open(src) as img:
        shift(img).save(dst, 'WEBP', quality=quality, method=4)
    return 'ok'


def main():
    sources = set()
    for pack in sorted(glob.glob(os.path.join(ROOT, 'js/frames/pack*.js'))):
        with open(pack, encoding='utf-8') as f:
            text = f.read()
        for m in ENTRY.finditer(text):
            name, src = m.group(2), m.group(4)
            if OTHER_COLOR.search(name) or not src.endswith('.png'):
                continue
            if os.path.exists(os.path.join(ROOT, src[1:-4] + '.webp')):
                sources.add(src)
    jobs = []
    for src in sorted(sources):
        base = os.path.join(ROOT, src[1:-4])
        jobs.append((base + '.webp', base + '-purple.webp', 90))
        if os.path.exists(base + 'Thumb.webp'):
            jobs.append((base + 'Thumb.webp', base + '-purpleThumb.webp', 82))
    with ProcessPoolExecutor() as pool:
        results = list(pool.map(convert, jobs, chunksize=4))
    with open(os.path.join(ROOT, 'js/app/purple-frames.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/make-purple-frames.py. Do not edit.\n')
        f.write('// Blue frame images that have a "-purple" version next to them.\n')
        f.write('window.CS_PURPLE_FRAMES = [\n' + ',\n'.join('\t' + repr(s).replace("'", '"') for s in sorted(sources)) + '\n];\n')
    print('blue images:', len(sources), '| written:', results.count('ok'), '| up to date:', results.count('skip'))


if __name__ == '__main__':
    main()
