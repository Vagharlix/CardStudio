// Copies the "custom" frames of mtgcardbuilder.com (the purple frames and a few
// extras that the site adds at the end of some packs) into web/, as WebP.
//
// The site lists them per pack in /js/customFrames/Custom<pack>.json and keeps
// the images in /img/frames/customParts/. This script reads those lists for
// every pack of the app, downloads the images and their thumbnails, and writes
// web/js/app/custom-frames.js, which web/js/app/ui.js reads to add the frames
// to the packs.
//
// Usage: node scripts/import-site-custom-frames.mjs [--force]   (needs Internet)
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const SITE = 'https://mtgcardbuilder.com';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const web = path.join(root, 'web');
const framesDir = path.join(web, 'js/frames');
const outDir = path.join(web, 'img/frames/customParts');
const FORCE = process.argv.includes('--force');
// Entries the site's authors left behind while testing.
const SKIP_NAME = /^test/i;
const SAFE_SRC = /^\/img\/frames\/customParts\/([A-Za-z0-9_().,+'&-]+)\.png$/;

function packIds() {
  const ids = new Set();
  for (const f of fs.readdirSync(framesDir)) {
    const m = /^pack(.+)\.js$/.exec(f);
    if (m) ids.add(m[1]);
    if (/^group.+\.js$/.test(f)) {
      const text = fs.readFileSync(path.join(framesDir, f), 'utf8');
      for (const v of text.matchAll(/value\s*:\s*(['"])([^'"]+)\1/g)) if (v[2] !== 'disabled') ids.add(v[2]);
    }
  }
  return [...ids].sort();
}

async function get(url, attempt = 1) {
  try {
    const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0 (card-studio import)' } });
    if (res.status === 404) return null;
    if (!res.ok) throw new Error('HTTP ' + res.status);
    return Buffer.from(await res.arrayBuffer());
  } catch (e) {
    if (attempt >= 4) throw new Error(url + ': ' + e.message);
    await new Promise((r) => setTimeout(r, 1000 * 2 ** attempt));
    return get(url, attempt + 1);
  }
}

async function pool(items, size, fn) {
  const queue = items.slice();
  await Promise.all(Array.from({ length: size }, async () => {
    while (queue.length) await fn(queue.shift());
  }));
}

const lists = {};
await pool(packIds(), 6, async (id) => {
  const body = await get(`${SITE}/js/customFrames/Custom${encodeURIComponent(id)}.json`);
  if (!body) return;
  let entries;
  try { entries = JSON.parse(body.toString('utf8')); } catch { return; }
  if (!Array.isArray(entries)) return;
  const frames = entries
    .filter((e) => e && typeof e.name === 'string' && !SKIP_NAME.test(e.name) && SAFE_SRC.test(e.src || ''))
    .map((e) => ({ name: e.name, src: e.src }));
  if (frames.length) lists[id] = frames;
});

const images = [...new Set(Object.values(lists).flat().map((f) => f.src))].sort();
fs.mkdirSync(outDir, { recursive: true });
let written = 0, upToDate = 0;
const missing = [];
await pool(images, 6, async (src) => {
  const base = SAFE_SRC.exec(src)[1];
  const full = path.join(outDir, base + '.webp');
  const thumb = path.join(outDir, base + 'Thumb.webp');
  if (!FORCE && fs.existsSync(full) && fs.existsSync(thumb)) { upToDate++; return; }
  const png = await get(SITE + src);
  if (!png) { missing.push(src); return; }
  await sharp(png, { limitInputPixels: false })
    .webp({ quality: 90, alphaQuality: 100, smartSubsample: true, effort: 4 }).toFile(full);
  // The site's "...Thumb.png" files are full-size copies: make a small one
  // (whole card, 120 px high, like the other frame thumbnails).
  await sharp(png).resize({ height: 120 })
    .webp({ quality: 82, alphaQuality: 100, smartSubsample: true, effort: 4 }).toFile(thumb);
  written++;
});

// Drop list entries whose image could not be downloaded.
for (const id of Object.keys(lists)) {
  lists[id] = lists[id].filter((f) => !missing.includes(f.src));
  if (!lists[id].length) delete lists[id];
}
const sorted = Object.fromEntries(Object.keys(lists).sort().map((k) => [k, lists[k]]));
fs.writeFileSync(path.join(web, 'js/app/custom-frames.js'),
  '// Generated by scripts/import-site-custom-frames.mjs. Do not edit.\n' +
  '// Frames that mtgcardbuilder.com adds at the end of these packs (pack id -> frames).\n' +
  'window.CS_CUSTOM_FRAMES = ' + JSON.stringify(sorted, null, '\t') + ';\n');
console.log(`packs: ${Object.keys(sorted).length} | frames: ${Object.values(sorted).flat().length} | images: ${images.length} ` +
  `(written ${written}, up to date ${upToDate}, missing ${missing.length})`);
if (missing.length) console.log('missing on the site:\n  ' + missing.join('\n  '));
